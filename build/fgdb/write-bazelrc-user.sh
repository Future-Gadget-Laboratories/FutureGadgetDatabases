#!/usr/bin/env bash
#
# Write .bazelrc.user for a CCL-free cockroach-oss release build.
# The Cockroach .bazelrc try-imports this file. It is gitignored.
#
# Knobs (environment):
#   FGDB_BAZEL_OUTPUT_BASE   required, directory on the large disk
#   FGDB_BAZEL_DISK_CACHE    required, directory on the large disk
#   FGDB_LOCAL_CPU           default 24
#   FGDB_LOCAL_RAM_MB        default 81920 (80 GiB)
#   FGDB_BUILD_CHANNEL       default fgl-oss
#   FGDB_BUILD_TARGET_TRIPLE default x86_64-pc-linux-gnu
#   FGDB_EXTRA_BAZELRC       optional extra lines appended as-is
#
# stamp.sh does not read BUILD_CHANNEL from the environment. The channel
# is an argument of --workspace_status_command. Bazel splits unquoted
# spaces in a bazelrc line into separate arguments, and leftover words
# become build targets. The whole stamp option is therefore one quoted
# token, the same way .bazelrc build:crosslinux and
# pkg/cmd/publish-provisional-artifacts write it.

set -euo pipefail

if [[ $# -ne 1 ]]; then
  echo "usage: write-bazelrc-user.sh SRC_DIR" >&2
  exit 2
fi

src=$1
output_base=${FGDB_BAZEL_OUTPUT_BASE:?set FGDB_BAZEL_OUTPUT_BASE}
disk_cache=${FGDB_BAZEL_DISK_CACHE:?set FGDB_BAZEL_DISK_CACHE}
local_cpu=${FGDB_LOCAL_CPU:-24}
local_ram_mb=${FGDB_LOCAL_RAM_MB:-81920}
channel=${FGDB_BUILD_CHANNEL:-fgl-oss}
triple=${FGDB_BUILD_TARGET_TRIPLE:-x86_64-pc-linux-gnu}

# A space, quote, or shell metacharacter in any of these would either
# split into another Bazel target or be expanded while this file is written.
require_rc_token() {
  local name=$1
  local value=$2
  if [[ -z "$value" ]]; then
    echo "write-bazelrc-user.sh: ${name} is empty" >&2
    exit 1
  fi
  case "$value" in
    *[[:space:]]* | *"'"* | *'"'* | *'`'* | *'$'* | *'('* | *')'*)
      echo "write-bazelrc-user.sh: ${name} must be one Bazel token (no spaces or quotes)" >&2
      exit 1
      ;;
  esac
  case "$value" in
    *\\*)
      echo "write-bazelrc-user.sh: ${name} must be one Bazel token (no spaces or quotes)" >&2
      exit 1
      ;;
  esac
}

require_rc_token FGDB_BAZEL_OUTPUT_BASE "$output_base"
require_rc_token FGDB_BAZEL_DISK_CACHE "$disk_cache"
require_rc_token FGDB_BUILD_CHANNEL "$channel"
require_rc_token FGDB_BUILD_TARGET_TRIPLE "$triple"

case "$local_cpu" in
  '' | *[!0-9]*)
    echo "write-bazelrc-user.sh: FGDB_LOCAL_CPU must be a positive integer" >&2
    exit 1
    ;;
esac
case "$local_ram_mb" in
  '' | *[!0-9]*)
    echo "write-bazelrc-user.sh: FGDB_LOCAL_RAM_MB must be a positive integer" >&2
    exit 1
    ;;
esac
if [[ "$local_cpu" -lt 1 || "$local_ram_mb" -lt 1 ]]; then
  echo "write-bazelrc-user.sh: CPU and RAM must be at least 1" >&2
  exit 1
fi

mkdir -p "$output_base" "$disk_cache" "$src"

rc="${src}/.bazelrc.user"
{
  cat <<'EOF'
# Generated by build/fgdb/write-bazelrc-user.sh. Do not commit.
# Bazel splits unquoted spaces in this file into separate arguments.
# Leftover words become build targets. Quote any option whose value
# contains spaces.
EOF
  printf "startup '--output_base=%s'\n" "$output_base"
  printf "build '--disk_cache=%s'\n" "$disk_cache"
  cat <<'EOF'
# --config=ci turns nogo on. --config=nolintonbuild sets a different flag
# and does not turn nogo off. nogo_disable_flag forces the analyzers off
# so this release build does not spend RAM on them. Delete that one line
# to match upstream CI nogo.
build --config=ci
build --config=nolintonbuild
build --//build/toolchains:nogo_disable_flag
# Public downloaded crosstool for linux/amd64. crosslinuxbase is what
# upstream release builds use: the same platform as crosslinux, with no
# stamp command of its own. Do not use ./dev build --cross: that path
# docker-runs the private bazelbuilder image.
build --config=crosslinuxbase
build -c opt
EOF
  printf 'build --local_cpu_resources=%s\n' "$local_cpu"
  printf 'build --local_ram_resources=%s\n' "$local_ram_mb"
  # Matches publish-provisional-artifacts: one quoted option, args
  # target-triple, build-channel, build-type. The type "release" is what
  # verify-oss-binary.sh checks for. Channel is fgl-oss, not
  # official-binary. Do not add --config=force_build_cdeps here.
  printf "build '--workspace_status_command=./build/bazelutil/stamp.sh %s %s release'\n" \
    "$triple" "$channel"
  cat <<'EOF'
# Prebuilt public c-deps (including libgeos) stay on. Do not add
# --config=force_build_cdeps unless the host toolchain is known to match
# the v23.2.15 c-dep build.
EOF
} >"$rc"

if [[ -n "${FGDB_EXTRA_BAZELRC:-}" ]]; then
  # Appended as-is. Extra lines must already be valid bazelrc. Quote any
  # value that contains a space, or Bazel will treat the leftover words
  # as build targets.
  printf '\n%s\n' "$FGDB_EXTRA_BAZELRC" >>"$rc"
fi

echo "Wrote ${rc}:"
cat "$rc"
