func sqlDB(t *testing.T, bin, addr, database, q string) {
	t.Helper()
	sqlDBOut(t, bin, addr, database, q)
}

func sqlDBOut(t *testing.T, bin, addr, database, q string) string {
	t.Helper()
	cmd := exec.Command(bin, "sql", "--insecure", "--host="+addr, "--database="+database, "-e", q)
	out, err := cmd.CombinedOutput()
	if err != nil || strings.Contains(string(out), "ERROR") {
		t.Fatalf("sql %s: %v\n%s", database, err, out)
	}
	return string(out)
}

func backupAndCheck(t *testing.T, tool, srcURL, dest string) BackupResult {
	t.Helper()
	out := runTool(t, tool, "backup", "--json", "--url", srcURL, "--dest", dest, "--name", "lab", "--split-rows", "20000")
	var bres BackupResult
	if err := json.Unmarshal(out, &bres); err != nil {
		t.Fatalf("backup json: %v\n%s", err, out)
	}
	if !bres.OK {
		t.Fatalf("backup not ok: %s", bres.Error)
	}
	t.Logf("peak_rss_bytes=%d rows=%d tables=%d backup=%s", bres.PeakRSSBytes, bres.Rows, bres.Tables, bres.Backup)
	if bres.Rows < 50000 {
		t.Fatalf("rows = %d", bres.Rows)
	}
	// 50000 payloads of 640 bytes is about 32 MiB. Holding that table in
	// memory would push the process well past this cap.
	if bres.PeakRSSBytes == 0 {
		t.Fatal("peak RSS was not reported")
	}
	if bres.PeakRSSBytes > 96<<20 {
		t.Fatalf("peak RSS %d bytes is too high for a streamed backup", bres.PeakRSSBytes)
	}
	assertSplitParts(t, bres.Backup)
	return bres
}

func assertSplitParts(t *testing.T, backup string) {
	t.Helper()
	parts, err := filepath.Glob(filepath.Join(backup, "data", "shop", "public", "events.part*.pgcopy.gz"))
	if err != nil {
		t.Fatal(err)
	}
	if len(parts) < 2 {
		t.Fatalf("expected split files, found %v", parts)
	}
}

func verifyLatest(t *testing.T, tool, dest string, bres BackupResult) {
	t.Helper()
	vout := runTool(t, tool, "verify", "--json", "--src", filepath.Join(dest, "lab", "latest"))
	var vres VerifyResult
	if err := json.Unmarshal(vout, &vres); err != nil {
		t.Fatal(err)
	}
	if !vres.OK || vres.Rows != bres.Rows {
		t.Fatalf("verify %#v", vres)
	}
	writeIncomplete(t, dest)
	lout := runTool(t, tool, "list", "--json", "--src", filepath.Join(dest, "lab"))
	var lres ListResult
	if err := json.Unmarshal(lout, &lres); err != nil {
		t.Fatal(err)
	}
	assertLatest(t, lres, bres.Timestamp)
}

func writeIncomplete(t *testing.T, dest string) {
	t.Helper()
	incomplete := filepath.Join(dest, "lab", "19990101T000000Z")
	if err := os.MkdirAll(filepath.Join(incomplete, "data"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(incomplete, "data", "partial.csv.gz"), []byte("nope"), 0o644); err != nil {
		t.Fatal(err)
	}
}

func assertLatest(t *testing.T, lres ListResult, timestamp string) {
	t.Helper()
	for _, ts := range lres.Timestamps {
		if ts == "19990101T000000Z" {
			t.Fatal("incomplete backup was listed")
		}
	}
	if lres.Latest != timestamp {
		t.Fatalf("latest %q, backup timestamp %q", lres.Latest, timestamp)
	}
}

// clusterPair is the source and target used by one roundtrip restore.
type clusterPair struct {
	bin     string
	tool    string
	srcAddr string
	dstAddr string
	dstURL  string
	dest    string
	backup  BackupResult
}

func restoreAndCompare(t *testing.T, pair clusterPair) {
	t.Helper()
	bin, tool, srcAddr, dstAddr := pair.bin, pair.tool, pair.srcAddr, pair.dstAddr
	dstURL, dest, bres := pair.dstURL, pair.dest, pair.backup
	rout := runTool(t, tool, "restore", "--json", "--url", dstURL, "--src", filepath.Join(dest, "lab", "latest"))
	var rres RestoreResult
	if err := json.Unmarshal(rout, &rres); err != nil {
		t.Fatalf("restore json: %v\n%s", err, rout)
	}
	if !rres.OK {
		t.Fatalf("restore failed: %s\nincompatible=%v\nwarnings=%v", rres.Error, rres.Incompatible, rres.Warnings)
	}
	if rres.Rows != bres.Rows {
		t.Fatalf("restored rows %d, backup rows %d", rres.Rows, bres.Rows)
	}
	srcCmp := compareCluster(t, bin, srcAddr)
	dstCmp := compareCluster(t, bin, dstAddr)
	if srcCmp != dstCmp {
		t.Fatalf("source and target differ\nSOURCE:\n%s\nTARGET:\n%s", srcCmp, dstCmp)
	}
	srcSchema := strings.TrimSpace(sqlDBOut(t, bin, srcAddr, "shop", `SELECT create_statement FROM [SHOW CREATE TABLE tricky];`))
	dstSchema := strings.TrimSpace(sqlDBOut(t, bin, dstAddr, "shop", `SELECT create_statement FROM [SHOW CREATE TABLE tricky];`))
	if srcSchema != dstSchema {
		t.Fatalf("schema differs\nSOURCE:\n%s\nTARGET:\n%s", srcSchema, dstSchema)
	}
	if _, err := runToolErr(tool, "restore", "--json", "--url", dstURL, "--src", filepath.Join(dest, "lab", "latest")); err == nil {
		t.Fatal("restore did not refuse a swap blocked by dependent views")
	}
	sql(t, bin, dstAddr, true, `CREATE TABLE shop.public.keeper (id INT PRIMARY KEY); INSERT INTO shop.public.keeper VALUES (7);`)
	forced := runTool(t, tool, "restore", "--json", "--force=in-place", "--url", dstURL, "--src", filepath.Join(dest, "lab", "latest"))
	var fres RestoreResult
	if err := json.Unmarshal(forced, &fres); err != nil {
		t.Fatalf("force restore json: %v\n%s", err, forced)
	}
	if !fres.OK {
		t.Fatalf("force restore failed: %s", fres.Error)
	}
	again := compareCluster(t, bin, dstAddr)
	if srcCmp != again {
		t.Fatalf("force restore changed the copy\nSOURCE:\n%s\nTARGET:\n%s", srcCmp, again)
	}
	kept := strings.TrimSpace(sqlOut(t, bin, dstAddr, true, `SELECT id FROM shop.public.keeper;`))
	if !strings.Contains(kept, "7") {
		t.Fatalf("force restore removed an unrelated table: %s", kept)
	}
	wantUsers := strings.TrimSpace(sqlOut(t, bin, dstAddr, true, `SELECT count(*) FROM shop.public.users;`))
	bad := filepath.Join(dest, "lab", "force-failure")
	copyDir(t, bres.Backup, bad)
	corruptObjectsForRestoreFailure(t, bad)
	if _, err := runToolErr(tool, "restore", "--json", "--force", "--load", "copy", "--url", dstURL, "--src", bad); err == nil {
		t.Fatal("force restore accepted a malformed schema")
	}
	preserved := strings.TrimSpace(sqlOut(t, bin, dstAddr, true, `SELECT count(*) FROM shop.public.users;`))
	if preserved != wantUsers {
		t.Fatalf("failed force restore changed existing rows: got %s, want %s", preserved, wantUsers)
	}
	next := strings.TrimSpace(sqlOut(t, bin, dstAddr, true, `SELECT nextval('shop.public.unused_seq');`))
	if !strings.Contains(next, "1") {
		t.Fatalf("unused sequence nextval = %s, want 1", next)
	}
	sql(t, bin, dstAddr, true, `CREATE TABLE shop.public.notes (id INT PRIMARY KEY, user_id INT REFERENCES shop.public.users (id));`)
	sql(t, bin, dstAddr, true, `INSERT INTO shop.public.notes VALUES (1, 1);`)
	if _, err := runToolErr(tool, "restore", "--json", "--force", "--url", dstURL, "--src", filepath.Join(dest, "lab", "latest")); err == nil {
		t.Fatal("force restore cascaded through an unrelated foreign key")
	}
	notes := strings.TrimSpace(sqlOut(t, bin, dstAddr, true, `SELECT id, user_id FROM shop.public.notes;`))
	if !strings.Contains(notes, "1") {
		t.Fatalf("unrelated table was emptied: %s", notes)
	}
	paid := strings.TrimSpace(sqlOut(t, bin, dstAddr, true, `SELECT count(*) FROM shop.public.paid;`))
	if !strings.Contains(paid, "1") {
		t.Fatalf("force restore dropped views before the foreign-key check: %s", paid)
	}
	add := strings.TrimSpace(sqlDBOut(t, bin, dstAddr, "shop", `SELECT add(20, 22);`))
	if !strings.Contains(add, "42") {
		t.Fatalf("force restore dropped functions before the foreign-key check: %s", add)
	}
}

func compareCluster(t *testing.T, bin, addr string) string {
	t.Helper()
	return strings.TrimSpace(sqlOut(t, bin, addr, true, `
SELECT count(*) FROM shop.public.users;
SELECT count(*) FROM shop.public.orders;
SELECT count(*) FROM shop.public.paid;
SELECT name, tags::STRING, profile::STRING FROM shop.public.users ORDER BY id;
SELECT id, user_id, status, note FROM shop.public.orders ORDER BY id;
SELECT last_value FROM shop.public.order_seq;
SELECT count(*), min(id), max(id), min(length(payload)), max(length(payload)) FROM shop.public.events;
SELECT raw_config_sql FROM crdb_internal.zones WHERE database_name = 'shop' ORDER BY target;
SELECT grantee, privilege_type FROM [SHOW GRANTS ON TABLE shop.public.users] WHERE grantee = 'reporter';
SELECT ok FROM audit.public.checks;
SELECT id, note IS NULL, note, blank IS NULL, blank FROM shop.public.literals ORDER BY id;
SELECT id, n, twice FROM shop.public.calc;
SELECT md5(string_agg(
  id::STRING || ':' ||
  coalesce(raw::STRING, '<null>') || ':' ||
  amount::STRING || ':' ||
  label::STRING || ':' ||
  coalesce(doc::STRING, '<null>') || ':' ||
  values::STRING,
  ',' ORDER BY id
)) FROM shop.public.tricky;
SELECT id FROM shop.public.paid_mv ORDER BY id;
SELECT last_value FROM shop.public.unused_seq;
SELECT id, name FROM shop.public.people ORDER BY id;
SELECT count(*) FROM [SHOW TABLES FROM shop] WHERE table_name LIKE 'people_id_seq%';
`)) + "\n" + strings.TrimSpace(sqlDBOut(t, bin, addr, "shop", `
SELECT function_name FROM crdb_internal.create_function_statements WHERE database_name = 'shop' ORDER BY function_name;
SELECT procedure_name FROM crdb_internal.create_procedure_statements WHERE database_name = 'shop' ORDER BY procedure_name;
SELECT add(20, 22);
`))
}

func assertIncompatible(t *testing.T, bin, tool, dstURL, dstAddr, base string, bres BackupResult) {
	t.Helper()
	sql(t, bin, dstAddr, true, `DROP DATABASE IF EXISTS shop CASCADE; DROP DATABASE IF EXISTS audit CASCADE;`)
	badDir := filepath.Join(base, "bad", filepath.Base(bres.Backup))
	copyDir(t, bres.Backup, badDir)
	injectVector(t, badDir)
	badOut, err := runToolErr(tool, "restore", "--json", "--url", dstURL, "--src", badDir, "--database", "shop")
	if err == nil {
		t.Fatal("incompatible restore succeeded")
	}
	var bad RestoreResult
	if jerr := json.Unmarshal(badOut, &bad); jerr != nil {
		t.Fatalf("bad restore output: %v\n%s", jerr, badOut)
	}
	if !namesVector(bad.Incompatible) {
		t.Fatalf("incompatible list did not name vectors: %#v\n%s", bad.Incompatible, bad.Error)
	}
}

func injectVector(t *testing.T, badDir string) {
	t.Helper()
	objPath := filepath.Join(badDir, "objects.json")
	body, err := os.ReadFile(objPath)
	if err != nil {
		t.Fatal(err)
	}
	var objects ObjectsFile
	if err := json.Unmarshal(body, &objects); err != nil {
		t.Fatal(err)
	}
	objects.Statements = append(objects.Statements, Statement{
		Database: "shop",
		Kind:     "table",
		Object:   "shop.public.vectors",
		SQL:      "CREATE TABLE public.vectors (id INT PRIMARY KEY, v VECTOR(3));",
	})
	objects.Zones = append(objects.Zones, ZoneStatement{
		Object: "INDEX shop.public.orders@orders_user_id",
		Level:  "index",
		SQL:    "ALTER INDEX shop.public.orders@orders_pkey CONFIGURE ZONE USING gc.ttlseconds = 80000;",
	})
	rewritten, err := json.MarshalIndent(objects, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	rewritten = append(rewritten, '\n')
	if err := os.WriteFile(objPath, rewritten, 0o644); err != nil {
		t.Fatal(err)
	}
	patchDigest(t, filepath.Join(badDir, "manifest.json"), "objects_file", objPath)
}

func namesVector(problems []Problem) bool {
	for _, p := range problems {
		if strings.Contains(p.Object, "vectors") {
			return true
		}
	}
	return false
}

func assertShortTTLFails(t *testing.T, bin, tool, srcURL, srcAddr, base string) {
	t.Helper()
	sql(t, bin, srcAddr, true, `
CREATE DATABASE shortlived;
CREATE TABLE shortlived.public.t (id INT PRIMARY KEY);
INSERT INTO shortlived.public.t VALUES (1);
ALTER TABLE shortlived.public.t CONFIGURE ZONE USING gc.ttlseconds = 1;
`)
	_, err := runToolErr(tool, "backup", "--json", "--url", srcURL, "--dest", filepath.Join(base, "gc-fail"), "--database", "shortlived", "--name", "short")
	if err == nil {
		t.Fatal("backup with a 1 second gc.ttlseconds succeeded")
	}
	if !strings.Contains(err.Error(), "gc.ttlseconds") {
		t.Fatal(err)
	}
}

func assertExtendTTLReverts(t *testing.T, bin, tool, srcURL, srcAddr, base string) BackupResult {
	t.Helper()
	gcOut := runTool(t, tool, "backup", "--json", "--url", srcURL, "--dest", filepath.Join(base, "gc-ok"), "--database", "shortlived", "--name", "short", "--extend-gc-ttl", "1h")
	var gcRes BackupResult
	if err := json.Unmarshal(gcOut, &gcRes); err != nil {
		t.Fatal(err)
	}
	ttl := strings.TrimSpace(sqlOut(t, bin, srcAddr, true, `SELECT raw_config_sql FROM crdb_internal.zones WHERE table_name = 't' AND database_name = 'shortlived';`))
	if !strings.Contains(ttl, "gc.ttlseconds = 1") {
		t.Fatalf("ttl was not restored:\n%s", ttl)
	}
	zoneBody, err := os.ReadFile(filepath.Join(gcRes.Backup, "zones.sql"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(zoneBody), "gc.ttlseconds = 1") {
		t.Fatalf("backup kept the temporary ttl:\n%s", zoneBody)
	}
	if strings.Contains(string(zoneBody), "gc.ttlseconds = 3600") {
		t.Fatalf("backup recorded the raised ttl:\n%s", zoneBody)
	}
	return gcRes
}

func assertIndexZoneSkipped(t *testing.T, tool, dstURL, base string, gcRes BackupResult) {
	t.Helper()
	zoneDir := filepath.Join(base, "zone-skip", gcRes.Timestamp)
	copyDir(t, gcRes.Backup, zoneDir)
	injectIndexZone(t, zoneDir)
	zout := runTool(t, tool, "restore", "--json", "--url", dstURL, "--src", zoneDir, "--database", "shortlived")
	var zres RestoreResult
	if err := json.Unmarshal(zout, &zres); err != nil {
		t.Fatalf("zone restore json: %v\n%s", err, zout)
	}
	if !zres.OK {
		t.Fatalf("index zone should be skipped, not fail the restore: %s", zres.Error)
	}
	if !zoneSkipped(zres.Warnings) {
		t.Fatalf("expected an index zone warning, got %#v", zres.Warnings)
	}
}

