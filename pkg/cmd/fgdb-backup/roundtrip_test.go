func runTool(t *testing.T, tool string, args ...string) []byte {
	t.Helper()
	out, err := runToolErr(tool, args...)
	if err != nil {
		t.Fatalf("%s: %v\n%s", strings.Join(args, " "), err, out)
	}
	return out
}

func runToolErr(tool string, args ...string) ([]byte, error) {
	cmd := exec.Command(tool, args...)
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	err := cmd.Run()
	if err != nil {
		return stdout.Bytes(), fmt.Errorf("%w\n%s", err, stderr.String())
	}
	return stdout.Bytes(), nil
}

func copyDir(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if info.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		body, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, body, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
}

func corruptObjectsForRestoreFailure(t *testing.T, base string) {
	t.Helper()
	path := filepath.Join(base, "objects.json")
	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var objects map[string]any
	if err := json.Unmarshal(body, &objects); err != nil {
		t.Fatal(err)
	}
	statements, ok := objects["statements"].([]any)
	if !ok {
		t.Fatalf("objects statements: %#v", objects["statements"])
	}
	for _, value := range statements {
		statement, ok := value.(map[string]any)
		if ok && statement["kind"] == "table" {
			statement["sql"] = "CREATE TABLE ("
			break
		}
	}
	out, err := json.MarshalIndent(objects, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, append(out, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
	patchDigest(t, filepath.Join(base, "manifest.json"), "objects_file", path)
}

func patchDigest(t *testing.T, manifestPath, field, filePath string) {
	t.Helper()
	body, err := os.ReadFile(filePath)
	if err != nil {
		t.Fatal(err)
	}
	sum := sha256.Sum256(body)
	var manifest map[string]any
	mbody, err := os.ReadFile(manifestPath)
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(mbody, &manifest); err != nil {
		t.Fatal(err)
	}
	obj, ok := manifest[field].(map[string]any)
	if !ok {
		t.Fatalf("manifest field %s: %#v", field, manifest[field])
	}
	obj["sha256"] = hex.EncodeToString(sum[:])
	obj["bytes"] = float64(len(body))
	out, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(manifestPath, append(out, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
}

func tail(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[len(s)-n:]
}
